  }

-- | Second-stage HTLC transaction kind.
data HtlcTxKind = HtlcSuccess | HtlcTimeout
  deriving (Eq, Show)

-- | An expected HTLC-success or HTLC-timeout transaction.
data HtlcTxVector = HtlcTxVector
  { htv_kind   :: !HtlcTxKind
  , htv_htlc   :: !Int            -- ^ index into 'c_htlcs'
  , htv_output :: !Word32         -- ^ commitment output index spent
  , htv_tx     :: !BS.ByteString  -- ^ hex
  }

-- | A commitment transaction vector, with its HTLC transactions.
data CommitVector = CommitVector
  { cv_name              :: String
  , cv_to_local_msat     :: !Word64
  , cv_to_remote_msat    :: !Word64
  , cv_feerate_per_kw    :: !Word32
  , cv_dust_limit_sat    :: !Word64
  , cv_htlcs             :: ![Int]  -- ^ indices into 'c_htlcs'
  , cv_commit_tx         :: !BS.ByteString  -- ^ hex
  , cv_htlc_txs          :: ![HtlcTxVector]
  }

-- | One insert_secret call and whether the spec accepts it.
data StorageStep = StorageStep
  { ss_index  :: !Word64
  , ss_ok     :: !Bool
  , ss_secret :: !BS.ByteString  -- ^ hex
  }

-- | A secret storage vector.
data StorageVector = StorageVector
  { sv_name  :: String
  , sv_steps :: ![StorageStep]
  }

